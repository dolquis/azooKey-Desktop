"""Re-port japanese-usage-dictionary into data/homophone-notes.tsv (docs/homophone-notes-spec.md).

The source is pinned to one tag and checked against the SHA-256 that Mozc's src/MODULE.bazel
pins for the same archive. The output is deterministic: the same source gives the same bytes.

  python scripts/homophone_notes_porter.py --fetch           download, verify and write
  python scripts/homophone_notes_porter.py --archive X.zip   the same from a downloaded archive
  python scripts/homophone_notes_porter.py --source X.txt    from an extracted usage_dict.txt
  python scripts/homophone_notes_porter.py --verify FILE     check a TSV against section 3.2
"""

import argparse
import hashlib
import io
import os
import sys
import tempfile
import urllib.request
import zipfile
from pathlib import Path

PORTER_VERSION = "1"
ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUTPUT = ROOT / "data" / "homophone-notes.tsv"

SOURCE_REPO = "https://github.com/hiroyuki-komatsu/japanese-usage-dictionary"
SOURCE_TAG = "2025-01-25"
ARCHIVE_URL = f"{SOURCE_REPO}/archive/refs/tags/{SOURCE_TAG}.zip"
ARCHIVE_SHA256 = "140f24f71f7d78d5eb5b93a9c079f44f23728dca5ab16bf857fe8a3fa1bf20ed"
ARCHIVE_MEMBER = f"japanese-usage-dictionary-{SOURCE_TAG}/usage_dict.txt"
COPYRIGHT = "Copyright (c) 2011, Hiroyuki Komatsu, Shoji Ogura, Tsuyoshi Horo"

SOURCE_NEWLINE = "\\" + "n"  # The two characters the source writes for a line break.

HEADER = f"""\
# homophone-notes.tsv (UTF-8, LF). Generated by scripts/homophone_notes_porter.py v{PORTER_VERSION}; do not edit by hand.
# Format: <reading>\\t<surface>\\t<note>  (docs/homophone-notes-spec.md section 3.2)
# Derived from japanese-usage-dictionary {SOURCE_TAG}, usage_dict.txt: {SOURCE_REPO}
# SPDX-License-Identifier: BSD-2-Clause
# {COPYRIGHT}
# License: BSD-2-Clause; see THIRD_PARTY_LICENSES for full terms.
# Modified: the part-of-speech column is dropped and each note is shortened from the
#   source gloss by docs/homophone-notes-spec.md section 3.3.
"""


def shorten(gloss):
    """Section 3.3: the note for one source gloss, or "" when nothing is left."""
    if gloss.startswith("1. "):
        gloss = gloss[3:]
    gloss = gloss.split(SOURCE_NEWLINE, 1)[0]
    gloss = gloss.split("「", 1)[0]
    return gloss.removesuffix("。")


def parse_source(text):
    """The (reading, surface, gloss) rows of usage_dict.txt, in source order."""
    if text.startswith("﻿"):
        text = text[1:]
    rows = []
    for number, line in enumerate(text.splitlines(), 1):
        if not line:
            continue
        cols = line.split("\t")
        if len(cols) != 4:
            raise ValueError(f"source line {number}: expected four columns")
        rows.append((cols[0], cols[1], cols[3]))
    return rows


def convert(source_text):
    seen = set()
    rows = []
    for reading, surface, gloss in parse_source(source_text):
        if (reading, surface) in seen:
            continue  # Section 3.3: the first row of a repeated pair wins.
        seen.add((reading, surface))
        note = shorten(gloss)
        if note:
            rows.append((reading, surface, note))
    rows.sort(key=lambda row: (row[0], row[1]))
    text = HEADER + "".join("\t".join(row) + "\n" for row in rows)
    verify(text)
    return text


def _valid_column(column):
    return bool(column) and not any(ord(c) < 0x20 or ord(c) == 0x7F for c in column)


def verify(text):
    """Section 3.2 over every row; the number of rows. Raises ValueError otherwise."""
    if text.startswith("﻿") or "\r" in text or not text.endswith("\n"):
        raise ValueError("TSV must be BOM-free UTF-8 with LF endings")
    keys = []
    in_header = True
    for number, line in enumerate(text.split("\n")[:-1], 1):
        if line.startswith("#"):
            if not in_header:
                raise ValueError(f"line {number}: comment after the header")
            continue
        in_header = False
        cols = line.split("\t")
        if len(cols) != 3 or not all(_valid_column(col) for col in cols):
            raise ValueError(f"line {number}: expected three non-empty columns")
        keys.append((cols[0], cols[1]))
    if len(set(keys)) != len(keys):
        raise ValueError("repeated (reading, surface)")
    if keys != sorted(keys):
        raise ValueError("rows are not in (reading, surface) code point order")
    return len(keys)


def source_from_archive(data):
    digest = hashlib.sha256(data).hexdigest()
    if digest != ARCHIVE_SHA256:
        raise ValueError(f"archive SHA-256 {digest} does not match the pinned {ARCHIVE_SHA256}")
    with zipfile.ZipFile(io.BytesIO(data)) as archive:
        return archive.read(ARCHIVE_MEMBER).decode("utf-8")


def write_atomically(path, text):
    """Leaves either the old file or the whole new one, never a partial output."""
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, temp = tempfile.mkstemp(dir=path.parent, prefix=path.name + ".", suffix=".tmp")
    try:
        with os.fdopen(fd, "wb") as handle:
            handle.write(text.encode("utf-8"))
        os.replace(temp, path)
    except BaseException:
        Path(temp).unlink(missing_ok=True)
        raise


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--fetch", action="store_true")
    group.add_argument("--archive", type=Path)
    group.add_argument("--source", type=Path)
    group.add_argument("--verify", type=Path)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args(argv)
    if args.verify:
        print(f"verified {verify(args.verify.read_bytes().decode('utf-8'))} notes")
        return 0
    if args.fetch:
        with urllib.request.urlopen(ARCHIVE_URL, timeout=60) as response:
            source = source_from_archive(response.read())
    elif args.archive:
        source = source_from_archive(args.archive.read_bytes())
    else:
        source = args.source.read_bytes().decode("utf-8")
    text = convert(source)
    write_atomically(args.output, text)
    print(f"wrote {verify(text)} notes to {args.output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
